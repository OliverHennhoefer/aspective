"""Render committed benchmark results as Markdown."""

import numpy as np

from .suites import SUITES

METRIC_NAMES = {
    "accuracy": "accuracy",
    "r2": "R²",
    "brier": "Brier score",
    "roc_auc": "ROC AUC",
    "average_precision": "average precision",
}


def _fmt(v, digits=3):
    return "n/a" if v is None or (isinstance(v, float) and np.isnan(v)) else f"{v:.{digits}f}"


def _p(p):
    if p is None or np.isnan(p):
        return "n/a"
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def _display(result, value):
    """Scores are stored higher-is-better; show lower-is-better metrics with their usual sign."""
    if value is None:
        return None
    return value if result["higher_is_better"] else -value


def _gate(r, pending):
    if r["passed"]:
        return "PASS"
    return "FAIL (pending)" if r["name"] in pending else "**FAIL**"


def summary_table(results, pending=()):
    lines = [
        "| Benchmark | Candidate | vs predecessor | Datasets | Better / within margin / worse | "
        "Median Δ | p (non-inferior) | Verdict | Gate |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        for c in r["comparisons"]:
            delta = c["median_diff"]
            lines.append(
                f"| [{r['name']}](#{r['name']}) | {r['candidate']} | {c['baseline']} | {c['n_datasets']} | "
                f"{c['wins']} / {c['ties']} / {c['losses']} | {delta:+.3f} | {_p(c['p_noninferior'])} | "
                f"{c['verdict']} | {_gate(r, pending)} |"
            )
    return "\n".join(lines)


def section(r):
    metric = METRIC_NAMES[r["metric"]]
    direction = "higher" if r["higher_is_better"] else "lower"
    proto = r["protocol"]
    if r["suite"] == "adbench-classical":
        split = f"{proto['n_splits'] * proto['n_repeats']} stratified 70/30 splits, fit without labels"
    elif proto["train_size"]:
        split = f"{proto['n_splits'] * proto['n_repeats']} stratified splits with {proto['train_size']} training rows"
    else:
        split = f"{proto['n_repeats']}x repeated {proto['n_splits']}-fold CV"
    out = [f"### {r['name']}", ""]
    out.append(f"**{r['candidate']}** vs {', '.join(r['predecessors'])}"
               + (f" (references: {', '.join(r['references'])})" if r["references"] else "")
               + f". Suite `{r['suite']}` ({SUITES[r['suite']].description}), {split}. "
               f"Metric: {metric}, {direction} is better; margin {r['margin']}.")
    if r["notes"]:
        out += ["", r["notes"]]
    out.append("")
    for c in r["comparisons"]:
        out.append(f"- vs {c['baseline']}: **{c['verdict']}**. Median difference {c['median_diff']:+.4f}, "
                   f"mean {c['mean_diff']:+.4f} (positive favours the candidate); better on {c['wins']}, "
                   f"within margin on {c['ties']}, worse on {c['losses']} of {c['n_datasets']} datasets; "
                   f"non-inferiority p = {_p(c['p_noninferior'])}, two-sided Wilcoxon p = {_p(c['p_two_sided'])}.")
    if r["candidate_failures"]:
        errs = r["errors"].get(r["candidate"], {})
        out.append(f"- The candidate failed on: " + "; ".join(
            f"{d} ({errs.get(d, ['?'])[0]})" for d in r["candidate_failures"]))
    fr = r["friedman"]
    ranks = sorted(fr["ranks"].items(), key=lambda kv: kv[1])
    out.append(f"- Average ranks over {fr['n_datasets']} datasets where every model ran: "
               + ", ".join(f"{label} {rank:.2f}" for label, rank in ranks)
               + f". Nemenyi critical difference {fr['cd']:.2f}"
               + (f", Friedman p = {_p(fr['p'])}." if fr["p"] is not None and not np.isnan(fr["p"]) else "."))
    cand_time = sum(r["seconds"][r["candidate"]].values())
    times = ", ".join(f"{label} {sum(r['seconds'][label].values()) / max(cand_time, 1e-9):.2g}x"
                      for label in r["predecessors"])
    out.append(f"- Total fit and score time relative to the candidate: {times}.")

    labels = [r["candidate"], *r["predecessors"], *r["references"]]
    out += ["", "<details><summary>Per-dataset scores</summary>", "",
            "| Dataset | " + " | ".join(labels) + " |", "|---" * (len(labels) + 1) + "|"]
    for d in r["datasets"]:
        vals = [r["scores"][label][d] for label in labels]
        finite = [v for v in vals if v is not None]
        best = max(finite) if finite else None
        cells = []
        for v in vals:
            text = _fmt(_display(r, v))
            cells.append(f"**{text}**" if v is not None and best is not None and best - v < 5e-4 else text)
        out.append(f"| {d} | " + " | ".join(cells) + " |")
    out += ["", "</details>", ""]
    return "\n".join(out)


HEADER = """# Benchmark results

Generated by `python -m benchmarks report` from `benchmarks/results/*.json`.
Do not edit by hand. How the benchmark works and how to add a model:
[`benchmarks/README.md`](README.md).

**Gate.** A candidate passes when it runs without errors on every dataset of
its suite and is *non-inferior* to each predecessor: a one-sided Wilcoxon
signed-rank test over the per-dataset mean scores rejects, at α = 0.05, that
the candidate is typically worse by more than the margin (0.01 for accuracy,
R² and ROC AUC; 0.005 for the Brier score). Winning everywhere is not
required. "Superior" additionally means significantly better (two-sided
Wilcoxon, α = 0.05). "Inconclusive" fails the gate: the data do not show the
candidate is competitive. "FAIL (pending)" marks failures listed in
`PENDING` in `benchmarks/specs.py`: known open work that does not block CI,
while any other failure does.
"""


def render(results, pending=()):
    results = sorted(results, key=lambda r: r["name"])
    parts = [HEADER, "## Summary", "", summary_table(results, pending), "", "## Details", ""]
    parts += [section(r) for r in results]
    env = results[0]["environment"] if results else {}
    if env:
        parts.append(f"Environment of the last run: Python {env['python']}, NumPy {env['numpy']}, "
                     f"SciPy {env['scipy']}, scikit-learn {env['sklearn']}.")
    return "\n".join(parts) + "\n"
