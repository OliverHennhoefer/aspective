"""Render committed benchmark results as Markdown."""

import numpy as np

from . import stats
from .runner import comparison_diffs
from .suites import SUITES

METRIC_NAMES = {
    "accuracy": "accuracy",
    "r2": "R²",
    "brier": "Brier score",
    "roc_auc": "ROC AUC",
    "average_precision": "average precision",
}


def _fmt(v, digits=3):
    return "n/a" if v is None or (isinstance(v, float) and np.isnan(v)) else f"{v:.{digits}f}"


def _p(p):
    if p is None or np.isnan(p):
        return "n/a"
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def _display(result, value):
    """Scores are stored higher-is-better; show lower-is-better metrics with their usual sign."""
    if value is None:
        return None
    return value if result["higher_is_better"] else -value


def summary_table(results):
    lines = [
        "| Benchmark | Candidate | vs predecessor | Datasets | Better / within margin / worse | "
        "Median Δ | p (non-inferior) | Severe wins / losses | Verdict | Gate |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        for c in r["comparisons"]:
            delta = c["median_diff"]
            lines.append(
                f"| [{r['name']}](#{r['name']}) | {r['candidate']} | {c['baseline']} | {c['n_datasets']} | "
                f"{c['wins']} / {c['ties']} / {c['losses']} | {delta:+.3f} | {_p(c['p_noninferior'])} | "
                f"{c['severe_wins']} / {c['severe_losses']} | {c['verdict']} | {'PASS' if r['passed'] else '**FAIL**'} |"
            )
    return "\n".join(lines)


def section(r):
    metric = METRIC_NAMES[r["metric"]]
    direction = "higher" if r["higher_is_better"] else "lower"
    proto = r["protocol"]
    if r["suite"] == "adbench-classical":
        split = f"{proto['n_splits'] * proto['n_repeats']} stratified 70/30 splits, fit without labels"
    elif proto["train_size"]:
        split = f"{proto['n_splits'] * proto['n_repeats']} stratified splits with {proto['train_size']} training rows"
    else:
        split = f"{proto['n_repeats']}x repeated {proto['n_splits']}-fold CV"
    out = [f"### {r['name']}", ""]
    out.append(f"**{r['candidate']}** vs {', '.join(r['predecessors'])}"
               + (f" (references: {', '.join(r['references'])})" if r["references"] else "")
               + f". Suite `{r['suite']}` ({SUITES[r['suite']].description}), {split}. "
               f"Metric: {metric}, {direction} is better; margin {r['margin']}.")
    if r["notes"]:
        out += ["", r["notes"]]
    out.append("")
    for c in r["comparisons"]:
        out.append(f"- vs {c['baseline']}: **{c['verdict']}**. Median difference {c['median_diff']:+.4f}, "
                   f"mean {c['mean_diff']:+.4f} (positive favours the candidate); better on {c['wins']}, "
                   f"within margin on {c['ties']}, worse on {c['losses']} of {c['n_datasets']} datasets; "
                   f"non-inferiority p = {_p(c['p_noninferior'])}, two-sided Wilcoxon p = {_p(c['p_two_sided'])}. "
                   f"Severe (beyond {stats.SEVERE} margins): {c['severe_wins']} wins, {c['severe_losses']} losses, "
                   f"p = {_p(c['p_severe'])}.")
    if r["candidate_failures"]:
        errs = r["errors"].get(r["candidate"], {})
        out.append("- The candidate failed on: " + "; ".join(
            f"{d} ({errs.get(d, ['?'])[0]})" for d in r["candidate_failures"]))
    fr = r["friedman"]
    ranks = sorted(fr["ranks"].items(), key=lambda kv: kv[1])
    out.append(f"- Average ranks over {fr['n_datasets']} datasets where every model ran: "
               + ", ".join(f"{label} {rank:.2f}" for label, rank in ranks)
               + f". Nemenyi critical difference {fr['cd']:.2f}"
               + (f", Friedman p = {_p(fr['p'])}." if fr["p"] is not None and not np.isnan(fr["p"]) else "."))
    cand_time = sum(r["seconds"][r["candidate"]].values())
    times = ", ".join(f"{label} {sum(r['seconds'][label].values()) / max(cand_time, 1e-9):.2g}x"
                      for label in r["predecessors"])
    out.append(f"- Total fit and score time relative to the candidate: {times}.")

    labels = [r["candidate"], *r["predecessors"], *r["references"]]
    out += ["", "<details><summary>Per-dataset scores</summary>", "",
            "| Dataset | " + " | ".join(labels) + " |", "|---" * (len(labels) + 1) + "|"]
    for d in r["datasets"]:
        vals = [r["scores"][label][d] for label in labels]
        finite = [v for v in vals if v is not None]
        best = max(finite) if finite else None
        cells = []
        for v in vals:
            text = _fmt(_display(r, v))
            cells.append(f"**{text}**" if v is not None and best is not None and best - v < 5e-4 else text)
        out.append(f"| {d} | " + " | ".join(cells) + " |")
    out += ["", "</details>", ""]
    return "\n".join(out)


HEADER = """# Benchmark results

Generated by `uv run aspective-bench report` from `bench/results/*.json`.
Do not edit by hand. How the benchmark works and how to add a model:
[`bench/README.md`](README.md).

**Gate.** A candidate passes when it runs without errors on every dataset of
its suite and is *non-inferior* to each predecessor: a one-sided Wilcoxon
signed-rank test over the per-dataset mean scores rejects, at α = 0.05, that
the candidate is typically worse by more than the margin (0.01 for accuracy,
R² and ROC AUC; 0.005 for the Brier score). Winning everywhere is not
required, but severe losses (more than five margins) must not significantly
outnumber severe wins (one-sided sign test, α = 0.05), or the verdict is
"severe losses" and the gate fails. "Superior" additionally means
significantly better (two-sided Wilcoxon, α = 0.05). "Inconclusive" fails
the gate: the data do not show the candidate is competitive. Verdicts are
recomputed from the per-dataset scores every time the gate is checked.
"""

SHIFTS = (-1.5, -1.0, -0.5, 0.0, 0.5)


def operating_characteristics(results, n_sim=1000):
    """How often the gate passes a candidate whose true typical difference is known."""
    lines = [
        "## How reliable the gate is",
        "",
        "Pass rate of the gate for a candidate whose true typical difference to",
        "its predecessor is the given number of margins. Each row is simulated",
        "from the committed comparisons on that suite: their per-dataset",
        "differences are centred at zero, keeping the real spread and tails",
        "between datasets, resampled to the suite's size and shifted. At −1 margin",
        "and below, a pass is a false pass (the target is at most 5%); at 0 and",
        "above, a failure is a miss. Most of the spread is genuine variation",
        "between datasets, not fold noise, so only more datasets lower the miss",
        "rate without loosening the margin.",
        "",
        "| Suite | Datasets | Comparisons | " + " | ".join(f"{k:+.1f} m" for k in SHIFTS) + " |",
        "|---|---|---" + "|---" * len(SHIFTS) + "|",
    ]
    for (suite, margin), pools in sorted(comparison_diffs(results).items()):
        n = len(SUITES[suite].datasets)
        oc = stats.operating_characteristic(pools, margin, n, [k * margin for k in SHIFTS], n_sim=n_sim)
        lines.append(f"| `{suite}` (margin {margin}) | {n} | {len(pools)} | "
                     + " | ".join(f"{oc[k * margin]:.0%}" for k in SHIFTS) + " |")
    return "\n".join(lines + [""])


def leaderboards(results, standards=()):
    """One table per suite and protocol with every model run on it, side by side.

    Benchmarks on the same suite share their datasets and splits, so their
    candidates and baselines can be ranked together. A model that appears in
    several benchmarks under the same label and configuration is listed once.
    """
    groups = {}
    for r in [*results, *standards]:
        key = (r["suite"], r["metric"], tuple(sorted(r["protocol"].items())))
        groups.setdefault(key, []).append(r)
    out = [
        "## Leaderboards",
        "",
        "Every model run on a suite, ranked together over the datasets where all of",
        "them ran: the candidates, the vanilla predecessors they must keep up with,",
        "the references shown for context, and standard methods with default",
        "settings (`uv run aspective-bench standards`). Lower average rank is better. These tables are for",
        "orientation; the gate only compares each candidate with its own",
        "predecessors, configured like the candidate's building blocks.",
        "",
    ]
    for (suite, metric, protocol), rs in sorted(groups.items()):
        models, roles = {}, {}
        for r in rs:
            for label in [r["candidate"], *r["predecessors"], *r["references"]]:
                ident = (label, r["models"][label])
                name = label if all(k[0] != label or k == ident for k in models) else f"{label} ({r['name']})"
                if ident not in models:
                    models[ident] = (name, [r["scores"][label][d] for d in r["datasets"]])
                if r["name"].startswith("standards-"):
                    role = "standard"
                else:
                    role = "candidate" if label == r["candidate"] else \
                        "predecessor" if label in r["predecessors"] else "reference"
                order = ("candidate", "predecessor", "reference", "standard")
                roles[ident] = min(role, roles.get(ident, role), key=order.index)
        if len(models) < 3:
            continue
        idents = list(models)
        matrix = np.array([[np.nan if v is None else v for v in models[i][1]] for i in idents], float).T
        ranks, _, cd, n = stats.friedman_nemenyi(matrix)
        first = rs[0]
        proto = dict(protocol)
        extra = f", {proto['train_size']} training rows" if proto.get("train_size") else ""
        out += [f"### `{suite}`, {METRIC_NAMES[metric]}{extra}", "",
                f"{len(idents)} models on {n} of {len(first['datasets'])} datasets "
                f"(Nemenyi critical difference {cd:.2f}).", "",
                f"| Rank | Model | Role | Average rank | Mean {METRIC_NAMES[metric]} | Median {METRIC_NAMES[metric]} |",
                "|---|---|---|---|---|---|"]
        order = np.argsort(ranks, kind="stable")
        for place, j in enumerate(order, 1):
            ident = idents[j]
            col = matrix[:, j]
            col = col[~np.isnan(col)]
            mean = _display(first, float(np.mean(col))) if col.size else None
            median = _display(first, float(np.median(col))) if col.size else None
            out.append(f"| {place} | {models[ident][0]} | {roles[ident]} | {ranks[j]:.2f} | "
                       f"{_fmt(mean)} | {_fmt(median)} |")
        out.append("")
    return "\n".join(out)


def render(results, standards=()):
    results = sorted(results, key=lambda r: r["name"])
    parts = [HEADER, "## Summary", "", summary_table(results), "",
             leaderboards(results, standards), operating_characteristics(results), "## Details", ""]
    parts += [section(r) for r in results]
    env = results[0]["environment"] if results else {}
    if env:
        parts.append(f"Environment of the last run: Python {env['python']}, NumPy {env['numpy']}, "
                     f"SciPy {env['scipy']}, scikit-learn {env['sklearn']}.")
    return "\n".join(parts) + "\n"


CATALOG_HEADER = """# All models

Every model aspective has considered, and what became of it: the ones in
the package, the ones the [benchmark gate](benchmarks.md) removed, the ones
dropped before a benchmark could run, shortlisted ones not built yet, and
the ones left out because they already have a maintained home or are out of
scope. Negative results are kept on purpose: a published method that does
not beat its vanilla version on dozens of public datasets is worth knowing
about, and the code of every removed model stays in the git history at the
commit named.

Generated by `uv run aspective-bench report` from
[`catalog.py`](https://github.com/OliverHennhoefer/aspective/blob/main/bench/src/aspective_bench/catalog.py)
and the committed benchmark results; do not edit by hand.
"""


def _included_result(result):
    if result is None:
        return "not benchmarked yet"
    metric = METRIC_NAMES[result["metric"]]
    parts = [f"{c['verdict']} vs {c['baseline']} (median {metric} {_display(result, c['median_diff']):+.3f}, "
             f"{c['n_datasets']} datasets)" for c in result["comparisons"]]
    return "; ".join(parts)


def render_catalog(results):
    """``docs/models.md``: every model considered, with its paper and outcome."""
    from .catalog import ENTRIES, STATUSES

    by_name = {r["name"]: r for r in results}
    out = [CATALOG_HEADER, "| Status | Models |", "|---|---|"]
    for key, label in STATUSES.items():
        out.append(f"| [{label}](#{key.replace(' ', '-')}) | {sum(e.status == key for e in ENTRIES)} |")
    for key, label in STATUSES.items():
        entries = [e for e in ENTRIES if e.status == key]
        out += ["", f'## {label} {{#{key.replace(" ", "-")}}}', "",
                "| Model | Task | Paper | Improves on | " + ("Gate result" if key == "included" else "Why") + " |",
                "|---|---|---|---|---|"]
        for e in entries:
            why = _included_result(by_name.get(e.benchmark)) if key == "included" else e.note
            out.append(f"| `{e.name}` | {e.task} | {e.paper} | {e.improves_on} | {why} |")
    return "\n".join(out) + "\n"
